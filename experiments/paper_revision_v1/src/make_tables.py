"""Write the paper's main-evidence tables as LaTeX straight from results/*.csv (no hand-copied numbers).

Outputs reports/tables/tab_main_year.tex, tab_main_contrasts.tex, tab_main_secondary.tex. Each file is a
complete table environment with the label used in the manuscript, so the manuscript can \\input it.
"""
from __future__ import annotations

import pandas as pd

from revision_lib import RES_DIR, TAB_DIR, TA, TB

LABEL = {"PPML": "Gravity--PPML", "LightGBM": "LightGBM (bagged)", "Hybrid": "Hybrid", "ImportDemand": "Rank by import demand"}


def f3(x: float) -> str:
    return f"{x:.3f}".replace("-", "$-$")


def signed(x: float) -> str:
    return ("$+" if x >= 0 else "$-") + f"{abs(x):.3f}$"


def ci(lo: float, hi: float) -> str:
    return f"[{f3(lo)}, {f3(hi)}]"


def pval(p: float) -> str:
    return "$<0.001$" if p < 0.001 else f"{p:.3f}"


def table_by_year(by_year: pd.DataFrame, pools: pd.DataFrame) -> str:
    years = sorted(by_year.year.unique())
    lines = [r"\begin{table}[htbp]", r"\centering", r"\caption{NDCG@10 by evaluation year, " + f"{years[0]}--{years[-1]}" + r"}\label{tab:main_year}",
             r"\footnotesize", r"\begin{adjustbox}{max width=\textwidth}", r"\begin{tabular}{@{}ll" + "c" * (len(years) + 1) + "@{}}", r"\toprule",
             "Task & Model & " + " & ".join(map(str, years)) + r" & All \\", r"\midrule"]
    k10 = pools[(pools.K == 10) & ~pools.persistent]
    for task, name in ((TA, "Discovery"), (TB, "Expansion")):
        t = by_year[by_year.task == task].pivot(index="model", columns="year", values="mean")
        allm = k10[k10.task == task].groupby("model").ndcg.mean()
        best = {y: t[y].idxmax() for y in years}
        best_all = allm.idxmax()
        for i, m in enumerate(["PPML", "LightGBM", "Hybrid", "ImportDemand"]):
            cells = [(r"\textbf{" + f3(t.loc[m, y]) + "}") if best[y] == m else f3(t.loc[m, y]) for y in years]
            cells.append((r"\textbf{" + f3(allm[m]) + "}") if best_all == m else f3(allm[m]))
            lines.append((name if i == 0 else "") + f" & {LABEL[m]} & " + " & ".join(cells) + r" \\")
        cnt = by_year[(by_year.task == task) & (by_year.model == "Hybrid")].set_index("year")["count"]
        lines.append(r" & Pools with NDCG & " + " & ".join(str(int(cnt[y])) for y in years) + f" & {int(cnt.sum())} " + r"\\")
        if task == TA:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{adjustbox}", r"\par\smallskip",
              r"\begin{minipage}{0.97\textwidth}\scriptsize",
              r"Notes: Each cell averages NDCG@10 over the pools of that year with at least one relevant destination; ``All'' averages over all pools. "
              r"LightGBM is re-fitted for each year with five seeds and row/column subsampling; the hybrid combines it with PPML by equal-weight rank fusion. "
              r"Bold marks the best entry per year. Generated by experiments/paper\_revision\_v1/src/make\_tables.py.",
              r"\end{minipage}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def table_contrasts(ct: pd.DataFrame) -> str:
    sel = ct[(ct.period == "2018-2024") & (ct.K == 10) & (ct.metric == "ndcg") & ~ct.persistent]
    lines = [r"\begin{table}[htbp]", r"\centering", r"\caption{Paired NDCG@10 contrasts over 2018--2024 (primary tests in the first row of each block)}\label{tab:main_contrasts}",
             r"\footnotesize", r"\begin{adjustbox}{max width=\textwidth}", r"\begin{tabular}{@{}lccccccc@{}}", r"\toprule",
             r"Contrast & Mean A / mean B & Difference & 95\% CI & $t$, two-way & Years $>0$ & Year-level $p$ & Holm $p$ \\",
             r" & & (A $-$ B) & (HS2 blocks) & clustered & & & \\", r"\midrule"]
    for task, name in ((TA, "Discovery"), (TB, "Expansion")):
        s = sel[sel.task == task]
        lines.append(r"\multicolumn{8}{@{}l}{\emph{" + name + f" ({int(s.n.iloc[0])} pools)" + r"}} \\")
        for r in s.itertuples():
            a, b = r.contrast.split(" - ")
            lines.append(f"{LABEL[a]} $-$ {LABEL[b]} & {r.mean_a:.3f} / {r.mean_b:.3f} & {signed(r.estimate)} & {ci(r.ci_low, r.ci_high)} & "
                         f"{r.t_twoway:.2f} & {r.years_positive}/{r.n_years} & {r.p_year_signflip:.3f} & {pval(r.p_holm_family3)} " + r"\\")
        if task == TA:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{adjustbox}", r"\par\smallskip", r"\begin{minipage}{0.97\textwidth}\scriptsize",
              r"Notes: CI: HS2-block bootstrap. $t$: standard errors clustered by HS2 chapter and by year. Year-level $p$: exact sign-flip test on the annual mean differences. "
              r"Holm: family of three comparisons per task using HS2-block sign-flip $p$-values. Generated by make\_tables.py.",
              r"\end{minipage}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def table_secondary(ct: pd.DataFrame) -> str:
    base = ct[ct.period.eq("2018-2024")]
    def cell(task, a, b, metric, k, persistent=False):
        r = base[(base.task == task) & (base.contrast == f"{a} - {b}") & (base.metric == metric) & (base.K == k) & (base.persistent == persistent)].iloc[0]
        return f"{signed(r.estimate)} {ci(r.ci_low, r.ci_high)} ({r.years_positive}/{r.n_years})"
    lines = [r"\begin{table}[htbp]", r"\centering", r"\caption{Other cut-offs and metrics, 2018--2024: differences (A $-$ B) with 95\% intervals and years positive}\label{tab:main_secondary}",
             r"\footnotesize", r"\begin{adjustbox}{max width=\textwidth}", r"\begin{tabular}{@{}lccc@{}}", r"\toprule",
             r"\multicolumn{4}{@{}l}{\emph{Discovery: A = hybrid}} \\", r"Metric & B = LightGBM (bagged) & B = Gravity--PPML & B = import demand \\", r"\midrule"]
    pa = [("Hybrid", "LightGBM"), ("Hybrid", "PPML"), ("Hybrid", "ImportDemand")]
    for lab, metric, k, pers in (("NDCG@5", "ndcg", 5, False), ("NDCG@20", "ndcg", 20, False), ("Successes@10 per pool", "succ", 10, False),
                                 ("Hit@10", "hit", 10, False), (r"Persistent-entry NDCG@10$^{a}$", "ndcg", 10, True)):
        lines.append(lab + " & " + " & ".join(cell(TA, a, b, metric, k, pers) for a, b in pa) + r" \\")
    lines += [r"\midrule", r"\multicolumn{4}{@{}l}{\emph{Expansion: A = Gravity--PPML}} \\", r"Metric & B = hybrid & B = LightGBM (bagged) & B = import demand \\", r"\midrule"]
    pb = [("PPML", "Hybrid"), ("PPML", "LightGBM"), ("PPML", "ImportDemand")]
    for lab, metric, k in (("NDCG@5", "ndcg", 5), ("NDCG@20", "ndcg", 20), ("Positive expansions@10 per pool", "succ", 10)):
        lines.append(lab + " & " + " & ".join(cell(TB, a, b, metric, k) for a, b in pb) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{adjustbox}", r"\par\smallskip", r"\begin{minipage}{0.97\textwidth}\scriptsize",
              r"Notes: HS2-block bootstrap 95\% intervals; the figure in brackets after each interval is the number of years with a positive difference. "
              r"$^{a}$At least USD 50,000 in both year $y$ and $y+1$, so only 2018--2023 can be evaluated. Generated by make\_tables.py.",
              r"\end{minipage}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    by_year = pd.read_csv(RES_DIR / "main_by_year.csv")
    pools = pd.read_csv(RES_DIR / "pool_metrics.csv", dtype={"hs2": str})
    ct = pd.read_csv(RES_DIR / "main_contrasts.csv")
    for name, tex in (("tab_main_year.tex", table_by_year(by_year, pools)), ("tab_main_contrasts.tex", table_contrasts(ct)),
                      ("tab_main_secondary.tex", table_secondary(ct))):
        (TAB_DIR / name).write_text(tex)
        print("wrote", TAB_DIR / name)


if __name__ == "__main__":
    main()
